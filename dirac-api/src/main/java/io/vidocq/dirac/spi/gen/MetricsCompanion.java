package io.vidocq.dirac.spi.gen;

import java.util.List;
import java.util.function.Function;

/**
 * Compile-time metric metadata for one bean class, implemented by the
 * {@code <Bean>$$DiracMetrics} companion generated by the Dirac annotation
 * processor (codegen audit CG-05 — APT-first rule).
 *
 * <p>All names, units, tags and scopes are fully resolved at compile time
 * (same rules as the startup scan: {@code absolute}, class-level prefixes,
 * constructor metrics, {@code MetricRegistry.name(...)}). Gauges carry a plain
 * functional accessor calling the gauge method directly — no
 * {@code MethodHandles.privateLookupIn}, hence no {@code opens} requirement for
 * non-private gauge methods.</p>
 *
 * <p>Discovered by {@code DiracExtension} before the reflective startup scan:
 * ServiceLoader (module-layer aware, strict-JPMS friendly via
 * {@code provides ... with}) first, then the
 * {@code Class.forName(bean + "$$DiracMetrics")} naming convention. The scan
 * remains the documented fallback for classes compiled without the processor.</p>
 *
 * <p>Implementations must be stateless with a public no-arg constructor.</p>
 */
public interface MetricsCompanion {

    /** The bean class these metrics belong to. */
    Class<?> beanClass();

    /** Pre-registered {@code @Timed} metrics (methods and constructors). */
    List<MetricSpec> timers();

    /** Pre-registered {@code @Counted} metrics (methods and constructors). */
    List<MetricSpec> counters();

    /** {@code @Gauge} accessors. */
    List<GaugeSpec> gauges();

    /**
     * Fully-resolved timer/counter registration.
     *
     * @param name  final metric name (all naming rules already applied)
     * @param description metric description ({@code ""} when absent)
     * @param unit  metric unit (spec default {@code "none"} when absent)
     * @param tags  raw {@code key=value} declarations, validated/parsed at ingestion
     * @param scope normalized registry scope (e.g. {@code application})
     */
    record MetricSpec(String name, String description, String unit,
                      List<String> tags, String scope) {
        public MetricSpec {
            tags = List.copyOf(tags);
        }
    }

    /**
     * Fully-resolved gauge registration with its direct accessor.
     *
     * @param invoker calls the gauge method on the bean instance passed as
     *                argument (ignored for {@code staticMethod} gauges) and
     *                returns the boxed numeric value
     */
    record GaugeSpec(String name, String description, String unit,
                     List<String> tags, String scope,
                     boolean staticMethod, Function<Object, Number> invoker) {
        public GaugeSpec {
            tags = List.copyOf(tags);
        }
    }
}
